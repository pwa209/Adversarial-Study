function qualify_detector(signal_csv, Fs, release_dir, output_json, reference_id, layer_names)
% Repeated inference on a DECLARED real reference recording. This is runtime
% qualification, not clinical validation or confirmation of checkpoint variant.
    if nargin < 6, layer_names = {}; end
    assert(nargin >= 5 && strlength(string(reference_id)) > 0, ...
        'Provide reference-recording provenance ID');
    release_dir = char(java.io.File(release_dir).getCanonicalPath());
    signal_csv = char(java.io.File(signal_csv).getCanonicalPath());
    addpath(release_dir);
    checkpoint = fullfile(release_dir, 'trained_consciousness_detector.mat');
    expected = 'd8b5f89e9c958bddf0804e445a21ca8160a04f23494c1a94bd3e0e9bd134dd17';
    checkpoint_hash = study_hash(checkpoint);
    assert(strcmp(checkpoint_hash, expected), 'Checkpoint differs from pinned Figshare v2');
    assert(strcmp(study_hash(fullfile(release_dir, 'predict_consciousness_level.m')), ...
        'a9b6073428f86bc55b93666867d5d63e5af4de8310fae41e395b05ad73e6fa23'), 'Pinned wrapper changed');
    assert(strcmp(study_hash(fullfile(release_dir, 'remap_gcs_scale.m')), ...
        '9b1a8bfdfd1e0cd36425ab73f5d97232215ea9c482d9fd57fccc16c704f90c68'), 'Pinned mapping changed');
    assert(strcmp(study_hash(fullfile(release_dir, 'BoundedOutputLayer.m')), ...
        '96aeb138b1ddf6dc5c874c38501ad5015db6d3636b4ba1aaede98996c547033f'), 'Pinned bounded layer changed');
    signal = readmatrix(signal_csv);
    assert(isvector(signal) && all(isfinite(signal(:))) && std(signal(:)) > 0, ...
        'Reference must be one finite nonconstant cortical signal');
    assert(Fs > 90 && abs(numel(signal) / Fs - 10) <= 0.01, ...
        'Reference must provide ten seconds at sampling above 90 Hz');
    tic;
    first = qualified_predict(signal, Fs, release_dir, layer_names);
    second = qualified_predict(signal, Fs, release_dir, layer_names);
    seconds = toc;
    assert(abs(first.score - second.score) < 1e-8, 'Native repeated predictions differ');
    activation_repeats_verified = false;
    if strcmp(first.extraction_status, 'forward_correspondence_verified')
        assert(strcmp(second.extraction_status, 'forward_correspondence_verified'), 'Extraction failed on repeat');
        assert(abs(first.preclip_gcs - second.preclip_gcs) < 1e-8, 'Pre-bound output differs on repeat');
        names = fieldnames(first.activations);
        for index = 1:numel(names)
            a = double(first.activations.(names{index})); b = double(second.activations.(names{index}));
            assert(isequal(size(a), size(b)) && all(isfinite(a(:))) && all(isfinite(b(:))), ...
                'Repeated activations have invalid shape/values');
            assert(max(abs(a(:) - b(:))) <= 1e-7 * max(1, max(abs(a(:)))), ...
                'Qualified activation differs on repeat');
        end
        activation_repeats_verified = true;
    end
    record = struct('status', 'native_forward_pass_reproducible', ...
        'checkpoint_sha256', checkpoint_hash, ...
        'wrapper_sha256', study_hash(fullfile(release_dir, 'predict_consciousness_level.m')), ...
        'mapping_sha256', study_hash(fullfile(release_dir, 'remap_gcs_scale.m')), ...
        'bound_layer_sha256', study_hash(fullfile(release_dir, 'BoundedOutputLayer.m')), ...
        'helper_sha256', study_hash(which('qualified_predict')), ...
        'reference_id', char(reference_id), 'reference_sha256', study_hash(signal_csv), ...
        'reference_kind', 'analyst_declared_empirical_reference', ...
        'sfreq_hz', Fs, 'samples', numel(signal), 'score', first.score, 'gcs', first.gcs, ...
        'repeat_difference', abs(first.score - second.score), 'two_pass_seconds', seconds, ...
        'input_orientation', 'native_wrapper_row_vector', 'matlab_version', version, ...
        'toolboxes', ver, 'extraction_status', first.extraction_status, ...
        'activation_repeats_verified', activation_repeats_verified, ...
        'extraction_error', first.extraction_error, 'qualified_layers', {layer_names}, ...
        'clinical_validation', 'not_established', 'checkpoint_variant', 'unresolved');
    if ~strcmp(first.extraction_status, 'forward_correspondence_verified')
        record.qualified_layers = {};
    end
    assert(~isfile(output_json), 'Preserve existing qualification receipt; use a new filename');
    fid = fopen(output_json, 'w');
    assert(fid >= 0, 'Cannot create qualification output');
    closer = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fprintf(fid, '%s\n', jsonencode(record, 'PrettyPrint', true));
end
